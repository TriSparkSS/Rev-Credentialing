    public static function codes(): array
    {
        return array_keys(self::all());
    }

    public static function normalize(?string $state): ?string
    {
        if ($state === null) {
            return null;
        }

        $code = strtoupper(trim($state));

        if ($code === '') {
            return null;
        }

        if (isset(self::all()[$code])) {
            return $code;
        }

        $name = strtolower($state);
        foreach (self::all() as $abbr => $full) {
            if (strtolower($full) === $name) {
                return $abbr;
            }
        }

        return strlen($code) <= 2 ? $code : substr($code, 0, 2);
    }
